// Bundles each scenes/*.html (inlining its <script src>) into src/scenes.generated.ts
// so the app can hand the WebView a self-contained page. Photo backgrounds come from
// scenes/photos.json: each entry becomes its own page built from scenes/photo.html.
//   node scripts/build-scenes.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sceneDir = join(root, 'scenes');
const out = join(root, 'src', 'scenes.generated.ts');

const inline = (html) =>
  html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
    const js = readFileSync(join(sceneDir, src), 'utf8').replace(/<\/script/gi, '<\\/script');
    return `<script>\n${js}</script>`;
  });

const files = readdirSync(sceneDir)
  .filter((f) => f.endsWith('.html') && f !== 'index.html' && f !== 'photo.html')
  .sort();

const entries = files.map((file) => {
  const id = file.replace(/\.html$/, '');
  return `  ${JSON.stringify(id)}: ${JSON.stringify(inline(readFileSync(join(sceneDir, file), 'utf8')))},`;
});

// Photo backgrounds: one page per entry, the entry's data baked in.
const photosPath = join(sceneDir, 'photos.json');
const photos = existsSync(photosPath) ? JSON.parse(readFileSync(photosPath, 'utf8')) : [];
const template = inline(readFileSync(join(sceneDir, 'photo.html'), 'utf8'));
for (const p of photos) {
  const data = JSON.stringify({ image: p.image, focus: p.focus, recipe: p.recipe }).replace(/</g, '\\u003c');
  entries.push(`  ${JSON.stringify('photo-' + p.id)}: ${JSON.stringify(template.replace('/*PHOTO*/ null', data))},`);
}
const photoMeta = photos.map((p) => ({
  id: 'photo-' + p.id,
  title: p.title,
  caption: p.caption,
  hint: p.hint,
  background: p.background,
  tone: p.tone,
  credit: p.credit,
}));

writeFileSync(
  out,
  `// Generated by scripts/build-scenes.mjs from scenes/ — do not edit by hand.\n` +
    `export const sceneHtml: Record<string, string> = {\n${entries.join('\n')}\n};\n\n` +
    `export type PhotoMeta = {\n  id: string;\n  title: string;\n  caption: string;\n  hint: string;\n  background: string;\n  tone: 'dark' | 'light';\n  credit?: string;\n};\n\n` +
    `export const photoMeta: PhotoMeta[] = ${JSON.stringify(photoMeta, null, 2)};\n`
);
console.log(`Bundled ${files.length} scenes and ${photos.length} photo backgrounds → ${out}`);
