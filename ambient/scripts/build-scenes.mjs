// Bundles each scenes/*.html (inlining its <script src>) into src/scenes.generated.ts
// so the app can hand the WebView a self-contained page.
//   node scripts/build-scenes.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sceneDir = join(root, 'scenes');
const out = join(root, 'src', 'scenes.generated.ts');

const files = readdirSync(sceneDir)
  .filter((f) => f.endsWith('.html') && f !== 'index.html')
  .sort();

const entries = files.map((file) => {
  const id = file.replace(/\.html$/, '');
  const html = readFileSync(join(sceneDir, file), 'utf8').replace(
    /<script src="([^"]+)"><\/script>/g,
    (_, src) => {
      const js = readFileSync(join(sceneDir, src), 'utf8').replace(/<\/script/gi, '<\\/script');
      return `<script>\n${js}</script>`;
    }
  );
  return `  ${JSON.stringify(id)}: ${JSON.stringify(html)},`;
});

writeFileSync(
  out,
  `// Generated by scripts/build-scenes.mjs from scenes/*.html — do not edit by hand.\n` +
    `export const sceneHtml: Record<string, string> = {\n${entries.join('\n')}\n};\n`
);
console.log(`Bundled ${files.length} scenes → ${out}`);
